#!/usr/bin/env python3
"""Generate the periphery and macro-top xschem schematics + symbols (issue #203).

Like design/generate_array.py, this is a *schematic-source generator*: it
writes plain-text xschem ``.sch``/``.sym`` files directly, using the same
label-net technique (nets merge by matching ``lab=`` text on lab_pin /
ipin / opin / iopin instances, no routed wires between instances). **xschem
itself, via `klt netlist`, is what turns the output into SPICE** -- this
script never writes a netlist. The output is a pure function of this file
(no clock or environment content), so re-running reproduces it byte-for-byte.

Architecture: spec/periphery-architecture.md (#202). This file owns the
transistor sizing that record leaves open; every W/L below is a first-cut
smoke-sim value, not an optimised or characterised one (design/README.md,
"Periphery sizing").

Hierarchy (every block is one .sch + one .sym + one netlist/*.spice):

  sram_256x32 (macro top, exactly the #198 pins + VDD/VSS)
    sram_64x128_array   the 4:1 physical array (generate_array.py)
    sram_ctrl           input flops, self-timed pulse generation
    row_path            two 3->8 predecoders + 64 AND2 row drivers
    col_decode          A[1:0] -> csel/cseln (gated by wl_en)
    precharge_slice x32 precharge/equalise for 4 columns of one I/O
    io_slice x32        mux (4 TGs/line), sense amp, write driver, D/WEN/Q flops
  leaf cells: inv*, nand*, nor3, and*, rowdrv, tg*, dff, sa_latch, wdrv

Usage:
    python3 design/generate_periphery.py [--outdir design]
"""
from __future__ import annotations

import argparse
import os

L_MIN = "0.28u"

# --- self-timed delay-chain lengths (stage counts of inv_dly) -------------
# Tuned against the nominal-corner control smoke sim; see design/README.md
# "Self-timed control". Odd N_PULSE (the chain inverts), even for the rest.
N_PULSE = 35  # CLK rise -> pulse end: sets the internal pulse width
N_DEC = 6  # pulse start -> wl_en rise: address decode settles first
N_BL = 6  # wl_en rise -> s_en rise: bit-line differential develops
N_QCLK = 4  # s_en rise -> Q-register capture clock

ROWS, COLS = 64, 128
IOS = 32
MUX = 4


# ---------------------------------------------------------------------------
# tiny schematic/symbol model
# ---------------------------------------------------------------------------
class Cell:
    def __init__(self, name, ins, outs, inouts=("VDD", "VSS"), doc=""):
        self.name = name
        self.ins = list(ins)
        self.outs = list(outs)
        self.inouts = list(inouts)
        self.doc = doc
        self.devs = []  # (name, kind, d, g, s, w, l)
        self.insts = []  # (name, cell, {pin: net})

    def n(self, name, d, g, s, w, l=L_MIN):
        self.devs.append((name, "n", d, g, s, w, l))

    def p(self, name, d, g, s, w, l=L_MIN):
        self.devs.append((name, "p", d, g, s, w, l))

    def x(self, name, cell, **pins):
        self.insts.append((name, cell, pins))

    @property
    def ports(self):
        return self.ins + self.outs + self.inouts


def _stub_pin_sides(cell):
    """symbol pin placement: inputs left, outputs right, VDD top, VSS bottom."""
    pitch = 20
    supplies = ("VDD", "VSS")
    left = cell.ins
    right = cell.outs + [p for p in cell.inouts if p not in supplies]
    rows = max(len(left), len(right), 2)
    half_h = (rows * pitch) // 2 + pitch
    pins = {}
    for i, name in enumerate(left):
        pins[name] = (-40, -half_h + pitch + i * pitch, "L")
    for i, name in enumerate(right):
        pins[name] = (40, -half_h + pitch + i * pitch, "R")
    pins["VDD"] = (0, -half_h - 20, "T")
    pins["VSS"] = (0, half_h + 20, "B")
    return pins, half_h


def emit_sym(cell):
    pins, half_h = _stub_pin_sides(cell)
    out = [
        "v {xschem version=3.4.7 file_version=1.2",
        f"* {cell.name} symbol -- MACHINE-GENERATED by design/generate_periphery.py",
        "}",
        "G {}",
        f'K {{type=subcircuit\nformat="@spiceprefix@name @pinlist {cell.name}"\n'
        'template="name=x1\nspiceprefix=X"\n}',
        "V {}",
        "S {}",
        "E {}",
        f"L 4 -40 {-half_h} 40 {-half_h} {{}}",
        f"L 4 -40 {half_h} 40 {half_h} {{}}",
        f"L 4 -40 {-half_h} -40 {half_h} {{}}",
        f"L 4 40 {-half_h} 40 {half_h} {{}}",
    ]
    for num, name in enumerate(cell.ports, 1):
        x, y, _ = pins[name]
        d = "in" if name in cell.ins else "out" if name in cell.outs else "inout"
        out.append(
            f"B 5 {x - 2} {y - 2} {x + 2} {y + 2} "
            f"{{name={name} dir={d} pinnumber={num}}}"
        )
    for name in cell.ports:
        x, y, side = pins[name]
        tx = x + 5 if side == "L" else x - 5 if side == "R" else x + 5
        ty = y + (0 if side in "LR" else (10 if side == "T" else -10))
        mir = 1 if side == "R" else 0
        out.append(f"T {{{name}}} {tx} {ty} 0 {mir} 0.2 0.2 {{}}")
    out.append(f"T {{@name}} -38 {half_h + 45} 0 0 0.2 0.2 {{}}")
    out.append(f"T {{{cell.name}}} -38 {-half_h + 5} 0 0 0.2 0.2 {{}}")
    return "\n".join(out) + "\n"


def emit_sch(cell, symcache):
    out = [
        "v {xschem version=3.4.7 file_version=1.2",
        f"* {cell.name} -- MACHINE-GENERATED by design/generate_periphery.py;",
        "* do not hand-edit, re-run the generator (see design/README.md).",
    ]
    for line in cell.doc.strip().splitlines():
        out.append("* " + line)
    out += ["}", "G {}", "K {}", "V {}", "S {}", "E {}"]
    ids = iter(range(1, 10**7))

    def lab(x, y, net):
        out.append(f"C {{lab_pin.sym}} {x} {y} 0 0 {{name=l{next(ids)} lab={net}}}")

    def stub(x0, y0, x1, y1, net):
        out.append(f"N {x0} {y0} {x1} {y1} {{}}")
        lab(x1, y1, net)

    # transistors in one row; xschem y grows downward. nfet: D up, S down;
    # pfet: D down, S up (same stub convention as bitcell_6t.sch).
    for i, (name, kind, d, g, s, w, l) in enumerate(cell.devs):
        x, y = i * 200, 0
        sym = "nfet_03v3" if kind == "n" else "pfet_03v3"
        bulk = "VSS" if kind == "n" else "VDD"
        out.append(
            f"C {{symbols/{sym}.sym}} {x} {y} 0 0 "
            f"{{name={name} model={sym} W={w} L={l} nf=1 m=1}}"
        )
        dy, sy = (-30, 30) if kind == "n" else (30, -30)
        stub(x + 20, y + dy, x + 20, y + dy + (dy // 30) * 20, d)
        stub(x + 20, y + sy, x + 20, y + sy + (sy // 30) * 20, s)
        stub(x - 20, y, x - 40, y, g)
        stub(x + 20, y, x + 40, y, bulk)

    # sub-cell instances stacked below the transistor row
    y = 400
    prev_half = 0
    for name, sub, pins in cell.insts:
        spins, half_h = symcache[sub]
        y += prev_half + half_h + (200 if prev_half else 0)
        prev_half = half_h
        out.append(f"C {{{sub}.sym}} 0 {y} 0 0 {{name={name}}}")
        for pin, (px, py, side) in spins.items():
            net = pins[pin]
            if side == "L":
                stub(px, y + py, px - 20, y + py, net)
            elif side == "R":
                stub(px, y + py, px + 20, y + py, net)
            elif side == "T":
                stub(px, y + py, px, y + py - 20, net)
            else:
                stub(px, y + py, px, y + py + 20, net)
        extra = set(pins) - set(spins)
        assert not extra, f"{cell.name}/{name}: unknown pins {extra}"
        assert set(spins) <= set(pins), (
            f"{cell.name}/{name}: unconnected pins {set(spins) - set(pins)}"
        )

    # top-level ports (label-matched, not wired -- same as bitcell_6t.sch)
    px = -400
    for i, name in enumerate(cell.ins):
        out.append(f"C {{ipin.sym}} {px} {-200 - 60 * i} 0 0 {{name=p{next(ids)} lab={name}}}")
    for i, name in enumerate(cell.outs):
        out.append(f"C {{opin.sym}} {px - 300} {-200 - 60 * i} 0 0 {{name=p{next(ids)} lab={name}}}")
    for i, name in enumerate(cell.inouts):
        out.append(f"C {{iopin.sym}} {px - 600} {-200 - 60 * i} 0 0 {{name=p{next(ids)} lab={name}}}")
    return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# leaf cells
# ---------------------------------------------------------------------------
def fmt(w):
    s = f"{w:g}"
    return s + "u"


def inv(name, wn, wp, l=L_MIN):
    c = Cell(name, ["a"], ["y"])
    c.p("MP", "y", "a", "VDD", fmt(wp), l)
    c.n("MN", "y", "a", "VSS", fmt(wn), l)
    return c


def nand(name, n, wn, wp, out_inv=None):
    """NAND-n; if out_inv=(wn, wp) the output is inverted (AND-n)."""
    ins = [f"a{i}" for i in range(n)]
    c = Cell(name, ins, ["y"])
    y = "nb" if out_inv else "y"
    for i in range(n):
        c.p(f"MP{i}", y, ins[i], "VDD", fmt(wp))
    nets = [y] + [f"s{i}" for i in range(1, n)] + ["VSS"]
    for i in range(n):
        c.n(f"MN{i}", nets[i], ins[i], nets[i + 1], fmt(wn))
    if out_inv:
        c.p("MPO", "y", "nb", "VDD", fmt(out_inv[1]))
        c.n("MNO", "y", "nb", "VSS", fmt(out_inv[0]))
    return c


def nor3(name, wn, wp):
    c = Cell(name, ["a0", "a1", "a2"], ["y"])
    c.p("MP0", "t1", "a0", "VDD", fmt(wp))
    c.p("MP1", "t2", "a1", "t1", fmt(wp))
    c.p("MP2", "y", "a2", "t2", fmt(wp))
    for i in range(3):
        c.n(f"MN{i}", "y", f"a{i}", "VSS", fmt(wn))
    return c


def tgate(name, wn, wp):
    c = Cell(name, ["a", "en", "enb"], [], inouts=["b", "VDD", "VSS"])
    # a/b are symmetric; 'b' is an inout so the symbol pin lists stay honest.
    c.n("MN", "a", "en", "b", fmt(wn))
    c.p("MP", "a", "enb", "b", fmt(wp))
    return c


def dff():
    c = Cell("dff", ["d", "clk"], ["q", "qb"])
    c.x("Xckb", "inv", a="clk", y="ckb", VDD="VDD", VSS="VSS")
    c.x("Xckp", "inv", a="ckb", y="ckp", VDD="VDD", VSS="VSS")
    # master: transparent while clk low
    c.x("Xtm", "tg_s", a="d", en="ckb", enb="ckp", b="m", VDD="VDD", VSS="VSS")
    c.x("Xnm", "inv", a="m", y="nm", VDD="VDD", VSS="VSS")
    c.x("Xmf", "inv", a="nm", y="mf", VDD="VDD", VSS="VSS")
    c.x("Xtmf", "tg_s", a="mf", en="ckp", enb="ckb", b="m", VDD="VDD", VSS="VSS")
    # slave: transparent while clk high
    c.x("Xts", "tg_s", a="nm", en="ckp", enb="ckb", b="s", VDD="VDD", VSS="VSS")
    c.x("Xns", "inv", a="s", y="q", VDD="VDD", VSS="VSS")
    c.x("Xsf", "inv", a="q", y="qb", VDD="VDD", VSS="VSS")
    c.x("Xtsf", "tg_s", a="qb", en="ckb", enb="ckp", b="s", VDD="VDD", VSS="VSS")
    c.doc = (
        "Positive-edge D flip-flop, transmission-gate master/slave, static.\n"
        "q follows d at the rising clk edge; qb = ~q."
    )
    return c


def sa_latch():
    c = Cell("sa_latch", ["s_en", "eqn"], [], inouts=["bl", "blb", "VDD", "VSS"])
    c.p("MPA", "bl", "blb", "VDD", "1u")
    c.p("MPB", "blb", "bl", "VDD", "1u")
    c.n("MNA", "bl", "blb", "tail", "1u")
    c.n("MNB", "blb", "bl", "tail", "1u")
    c.n("MNT", "tail", "s_en", "VSS", "2u")
    # keep the latch nodes at VDD whenever no access is in flight
    c.p("MPE1", "bl", "eqn", "VDD", "1u")
    c.p("MPE2", "blb", "eqn", "VDD", "1u")
    c.doc = (
        "Latch-type (cross-coupled) sense amp wired directly to the muxed\n"
        "bit-line pair. s_en high fires it; eqn low holds both nodes at VDD."
    )
    return c


def wdrv():
    c = Cell("wdrv", ["d", "wen", "wpn"], [], inouts=["bl", "blb", "VDD", "VSS"])
    c.x("Xdn", "inv", a="d", y="dn", VDD="VDD", VSS="VSS")
    c.x("Xpl", "nor3", a0="wen", a1="wpn", a2="d", y="pl", VDD="VDD", VSS="VSS")
    c.x("Xpr", "nor3", a0="wen", a1="wpn", a2="dn", y="pr", VDD="VDD", VSS="VSS")
    c.n("MNWL", "bl", "pl", "VSS", "1.5u")
    c.n("MNWR", "blb", "pr", "VSS", "1.5u")
    c.doc = (
        "Write driver. Writes bit-line side that matches ~d to VSS when\n"
        "wen=0 (active low, per bit) and wpn=0 (write pulse, active low).\n"
        "d=0 pulls bl low, d=1 pulls blb low."
    )
    return c


def precharge_slice():
    ins = [f"csel{s}" for s in range(MUX)]
    io = [f"bl{s}" for s in range(MUX)] + [f"blb{s}" for s in range(MUX)]
    c = Cell("precharge_slice", ins, [], inouts=io + ["VDD", "VSS"])
    for s in range(MUX):
        c.p(f"MPB{s}", f"bl{s}", f"csel{s}", "VDD", "1u")
        c.p(f"MPN{s}", f"blb{s}", f"csel{s}", "VDD", "1u")
        c.p(f"MPE{s}", f"bl{s}", f"csel{s}", f"blb{s}", "1u")
    c.doc = (
        "Bit-line precharge/equalise for the MUX=4 columns of one I/O.\n"
        "csel[s] high (column s selected, access in flight) releases that\n"
        "column; unselected columns stay precharged (half-select protection,\n"
        "periphery record row 9)."
    )
    return c


def io_slice():
    ins = (
        [f"csel{s}" for s in range(MUX)]
        + [f"cseln{s}" for s in range(MUX)]
        + ["d_in", "wen_in", "clk", "q_clk", "s_en", "wl_en_n", "wpn"]
    )
    io = [f"bl{s}" for s in range(MUX)] + [f"blb{s}" for s in range(MUX)]
    c = Cell("io_slice", ins, ["q_out"], inouts=io + ["VDD", "VSS"])
    for s in range(MUX):
        c.x(f"Xmb{s}", "tg_mux", a=f"bl{s}", b="mbl", en=f"csel{s}", enb=f"cseln{s}", VDD="VDD", VSS="VSS")
        c.x(f"Xmn{s}", "tg_mux", a=f"blb{s}", b="mblb", en=f"csel{s}", enb=f"cseln{s}", VDD="VDD", VSS="VSS")
    c.x("Xfd", "dff", d="d_in", clk="clk", q="dq", qb="dqb", VDD="VDD", VSS="VSS")
    c.x("Xfw", "dff", d="wen_in", clk="clk", q="wq", qb="wqb", VDD="VDD", VSS="VSS")
    c.x("Xwd", "wdrv", d="dq", wen="wq", wpn="wpn", bl="mbl", blb="mblb", VDD="VDD", VSS="VSS")
    c.x("Xsa", "sa_latch", s_en="s_en", eqn="wl_en_n", bl="mbl", blb="mblb", VDD="VDD", VSS="VSS")
    c.x("Xfq", "dff", d="mbl", clk="q_clk", q="q_out", qb="qnc", VDD="VDD", VSS="VSS")
    c.doc = (
        "One I/O slice (periphery record rows 3, 5-8, 10): 4 transmission-gate\n"
        "pass gates per bit line onto one shared pair (mbl/mblb) that feeds one\n"
        "latch sense amp and one write driver; D/WEN input flops on rising clk;\n"
        "Q register (flop clocked by q_clk, a read-only strobe, so Q holds\n"
        "across writes and idle cycles)."
    )
    return c


def row_path():
    ins = (
        [f"aq{k}" for k in range(2, 8)]
        + [f"aqb{k}" for k in range(2, 8)]
        + ["wl_en"]
    )
    outs = [f"wl{r}" for r in range(ROWS)]
    c = Cell("row_path", ins, outs)

    def lit(k, bit):  # literal of address bit k that is 1 when bit==1
        return f"aq{k}" if bit else f"aqb{k}"

    for h in range(8):  # A[7:5] predecode, gated by wl_en
        c.x(f"Xph{h}", "and4", a0=lit(7, h >> 2 & 1), a1=lit(6, h >> 1 & 1), a2=lit(5, h & 1),
            a3="wl_en", y=f"ph{h}", VDD="VDD", VSS="VSS")
    for j in range(8):  # A[4:2] predecode
        c.x(f"Xpl{j}", "and3", a0=lit(4, j >> 2 & 1), a1=lit(3, j >> 1 & 1), a2=lit(2, j & 1),
            y=f"pl{j}", VDD="VDD", VSS="VSS")
    for r in range(ROWS):
        c.x(f"Xrow{r}", "rowdrv", a0=f"ph{r >> 3}", a1=f"pl{r & 7}", y=f"wl{r}", VDD="VDD", VSS="VSS")
    c.doc = (
        "Row path (periphery record row 4): row = A[7:2]; two 3->8\n"
        "predecoders (A[7:5] gated with wl_en, A[4:2]) then a 2-input AND per\n"
        "row whose output stage is the wordline driver."
    )
    return c


def col_decode():
    ins = ["aq0", "aqb0", "aq1", "aqb1", "wl_en"]
    outs = [f"csel{s}" for s in range(MUX)] + [f"cseln{s}" for s in range(MUX)]
    c = Cell("col_decode", ins, outs)
    for s in range(MUX):
        a1 = "aq1" if s >> 1 & 1 else "aqb1"
        a0 = "aq0" if s & 1 else "aqb0"
        c.x(f"Xn{s}", "nand3", a0="wl_en", a1=a1, a2=a0, y=f"sn{s}", VDD="VDD", VSS="VSS")
        c.x(f"Xc{s}", "inv_x16", a=f"sn{s}", y=f"csel{s}", VDD="VDD", VSS="VSS")
        c.x(f"Xcn{s}", "inv_x16", a=f"csel{s}", y=f"cseln{s}", VDD="VDD", VSS="VSS")
    c.doc = (
        "Column select: A[1:0] decoded and gated by wl_en. csel[s] is the\n"
        "NMOS gate of the mux transmission gates (and releases the precharge),\n"
        "cseln[s] the PMOS gate. Physical column p = 4*i + s (record row 3)."
    )
    return c


def chain(c, prefix, src, dst, n, cell="inv_dly"):
    nets = [src] + [f"{prefix}{i}" for i in range(1, n)] + [dst]
    for i in range(n):
        c.x(f"X{prefix}{i}", cell, a=nets[i], y=nets[i + 1], VDD="VDD", VSS="VSS")


def ctrl():
    ins = [f"A{k}" for k in range(8)] + ["CEN", "GWEN", "CLK"]
    outs = (
        [f"aq{k}" for k in range(8)]
        + [f"aqb{k}" for k in range(8)]
        + ["clk_buf", "wl_en", "wl_en_n", "s_en", "q_clk", "wpn"]
    )
    c = Cell("sram_ctrl", ins, outs)
    V = dict(VDD="VDD", VSS="VSS")
    c.x("Xcb1", "inv", a="CLK", y="clkb", **V)
    c.x("Xcb2", "inv_x16", a="clkb", y="clk_buf", **V)
    for k in range(8):
        c.x(f"Xfa{k}", "dff", d=f"A{k}", clk="clk_buf", q=f"aq{k}", qb=f"aqb{k}", **V)
    c.x("Xfcen", "dff", d="CEN", clk="clk_buf", q="cenq", qb="en_q", **V)
    c.x("Xfgw", "dff", d="GWEN", clk="clk_buf", q="gwq", qb="gwqb", **V)
    c.x("Xrd", "and2", a0="en_q", a1="gwq", y="rd_q", **V)
    c.x("Xwr", "and2", a0="en_q", a1="gwqb", y="wr_q", **V)
    # pulse: p = clk_buf & ~delay(clk_buf); its width is the chain delay, not
    # the clock duty cycle.
    chain(c, "dp", "clk_buf", "dn", N_PULSE)
    c.x("Xpn", "nand2", a0="clk_buf", a1="dn", y="p_n", **V)
    c.x("Xp", "inv", a="p_n", y="p", **V)
    chain(c, "dd", "p", "p_d", N_DEC)
    c.x("Xwen", "nand3", a0="p", a1="p_d", a2="en_q", y="wl_en_i", **V)
    c.x("Xwe1", "inv_x8", a="wl_en_i", y="wl_en", **V)
    c.x("Xwe2", "inv_x8", a="wl_en", y="wl_en_n", **V)
    chain(c, "db", "wl_en", "wl_d2", N_BL)
    c.x("Xsn", "nand3", a0="wl_en", a1="wl_d2", a2="rd_q", y="s_en_i", **V)
    c.x("Xs1", "inv_x8", a="s_en_i", y="s_en", **V)
    chain(c, "dq", "s_en", "s_d", N_QCLK)
    c.x("Xqn", "nand2", a0="s_en", a1="s_d", y="q_clk_i", **V)
    c.x("Xq1", "inv_x8", a="q_clk_i", y="q_clk", **V)
    c.x("Xwn", "nand2", a0="wl_en", a1="wr_q", y="w_n", **V)
    c.x("Xw1", "inv_x4", a="w_n", y="w_p", **V)
    c.x("Xw2", "inv_x16", a="w_p", y="wpn", **V)
    c.doc = (
        "Control: input flops on rising CLK (A, CEN, GWEN), then a self-timed\n"
        "access (periphery record rows 10-11). p starts at the CLK rising edge\n"
        "and ends after the N_PULSE-stage delay chain; wl_en = p & delayed p &\n"
        "enable, so decode settles before the wordline fires and the pulse\n"
        "end is set by the delay path, not by the CLK falling edge. s_en\n"
        "(read only) fires N_BL stages after wl_en; q_clk (read only) strobes\n"
        "the Q registers N_QCLK stages after s_en; wpn is the active-low\n"
        "write pulse (write only)."
    )
    return c


def top(array_pins):
    ins = ["A[7:0]", "CEN", "GWEN", "CLK", "D[31:0]", "WEN[31:0]"]
    c = Cell("sram_256x32", ins, ["Q[31:0]"])
    V = dict(VDD="VDD", VSS="VSS")
    ctrl_pins = {f"A{k}": f"A[{k}]" for k in range(8)}
    ctrl_pins.update(CEN="CEN", GWEN="GWEN", CLK="CLK")
    for k in range(8):
        ctrl_pins[f"aq{k}"] = f"aq{k}"
        ctrl_pins[f"aqb{k}"] = f"aqb{k}"
    for n in ("clk_buf", "wl_en", "wl_en_n", "s_en", "q_clk", "wpn"):
        ctrl_pins[n] = n
    c.x("Xctrl", "sram_ctrl", **ctrl_pins, **V)
    rp = {f"aq{k}": f"aq{k}" for k in range(2, 8)}
    rp.update({f"aqb{k}": f"aqb{k}" for k in range(2, 8)})
    rp["wl_en"] = "wl_en"
    rp.update({f"wl{r}": f"WL{r}" for r in range(ROWS)})
    c.x("Xrow", "row_path", **rp, **V)
    cd = dict(aq0="aq0", aqb0="aqb0", aq1="aq1", aqb1="aqb1", wl_en="wl_en")
    for s in range(MUX):
        cd[f"csel{s}"] = f"csel{s}"
        cd[f"cseln{s}"] = f"cseln{s}"
    c.x("Xcol", "col_decode", **cd, **V)
    arr = {f"WL{r}": f"WL{r}" for r in range(ROWS)}
    for p in range(COLS):
        arr[f"BL{p}"] = f"BL{p}"
        arr[f"BLB{p}"] = f"BLB{p}"
    c.x("Xarray", "sram_64x128_array", **arr, **V)
    for i in range(IOS):
        pc = {f"csel{s}": f"csel{s}" for s in range(MUX)}
        sl = dict(pc)
        for s in range(MUX):
            pc[f"bl{s}"] = f"BL{MUX * i + s}"
            pc[f"blb{s}"] = f"BLB{MUX * i + s}"
            sl[f"bl{s}"] = f"BL{MUX * i + s}"
            sl[f"blb{s}"] = f"BLB{MUX * i + s}"
            sl[f"cseln{s}"] = f"cseln{s}"
        sl.update(d_in=f"D[{i}]", wen_in=f"WEN[{i}]", clk="clk_buf", q_clk="q_clk", s_en="s_en",
                  wl_en_n="wl_en_n", wpn="wpn", q_out=f"Q[{i}]")
        c.x(f"Xpc{i}", "precharge_slice", **pc, **V)
        c.x(f"Xio{i}", "io_slice", **sl, **V)
    c.doc = (
        "Macro top level -- the LVS reference for the macro. Ports are exactly\n"
        "the #198 pins (A[7:0], CEN, GWEN, CLK, D[31:0], WEN[31:0], Q[31:0])\n"
        "plus VDD/VSS; WL*/BL*/BLB* and every control net are internal."
    )
    return c


def array_cell():
    ins = [f"WL{r}" for r in range(ROWS)]
    io = [f"BL{p}" for p in range(COLS)] + [f"BLB{p}" for p in range(COLS)]
    # symbol only; the schematic is generate_array.py's output. Port order
    # matches that script's ipin/iopin emission order: WL*, then BL0/BLB0..
    c = Cell("sram_64x128_array", ins, [], inouts=[])
    c.inouts = []
    for p in range(COLS):
        c.inouts += [f"BL{p}", f"BLB{p}"]
    c.inouts += ["VDD", "VSS"]
    return c


def build():
    cells = [
        inv("inv", 0.5, 1.0),
        inv("inv_x4", 2, 4),
        inv("inv_x8", 4, 8),
        inv("inv_x16", 8, 16),
        inv("inv_dly", 0.5, 1.0, l="0.6u"),
        nand("nand2", 2, 1.0, 1.0),
        nand("nand3", 3, 1.5, 1.0),
        nand("and2", 2, 1.0, 1.0, out_inv=(0.5, 1.0)),
        nand("and3", 3, 1.5, 1.0, out_inv=(0.5, 1.0)),
        nand("and4", 4, 2.0, 1.0, out_inv=(1.0, 2.0)),
        nand("rowdrv", 2, 2.0, 2.0, out_inv=(3.0, 6.0)),
        nor3("nor3", 0.5, 2.0),
        tgate("tg_s", 0.5, 1.0),
        tgate("tg_mux", 2.0, 3.0),
        dff(),
        sa_latch(),
        wdrv(),
        precharge_slice(),
        io_slice(),
        row_path(),
        col_decode(),
        ctrl(),
    ]
    return cells


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outdir", default="design")
    args = ap.parse_args(argv)

    cells = build()
    arr = array_cell()
    t = top(None)
    allcells = cells + [t]
    symcache = {}
    for cell in cells + [arr, t]:
        symcache[cell.name] = _stub_pin_sides(cell)
    for cell in allcells:
        with open(os.path.join(args.outdir, f"{cell.name}.sch"), "w") as f:
            f.write(emit_sch(cell, symcache))
    for cell in cells + [arr]:
        with open(os.path.join(args.outdir, f"{cell.name}.sym"), "w") as f:
            f.write(emit_sym(cell))
    print(f"wrote {len(allcells)} schematics + {len(cells) + 1} symbols to {args.outdir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

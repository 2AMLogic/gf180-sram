#!/usr/bin/env python3
"""Macro write/read smoke test: testbench generator and result checker (#203).

    smoke.py gen   [--out sim/macro-smoke/testbench/tb_macro_write_read.spice]
    smoke.py check <ngspice-log>
    smoke.py gen-klt [--out ...] [--request-out ...]   # klt sim body + request (#217)
    smoke.py check-klt <klt-sim-report.json>

`gen` writes the testbench: a pure function of the OPS table below (explicit
PWL sources and `.meas` cards, no environment content), so the committed file
is reproducible. `check` parses the `.meas` lines from an ngspice log of that
testbench, rebuilds every sampled `Q` word and compares it with the expected
word, printing `RESULT:` lines in the repo's convention and exiting non-zero on
any mismatch. Single corner, functional only: no timing or margin is derived.
"""
from __future__ import annotations

import argparse
import re
import sys

PERIOD = 20.0  # ns
FIRST_EDGE = 5.0  # ns; edge 0 is an idle (CEN=1) initialisation cycle
CLK_HIGH = 10.0  # ns; must exceed the control pulse chain (~4.5 ns nominal)
SETUP = 6.0  # ns: inputs change this long before the edge, in the CLK-low phase
SAMPLE = 9.0  # ns after the edge at which Q is sampled (before CLK falls)
TRISE = 0.1
BL_STANDIN_FF = 20  # lumped bit-line capacitance for the unpopulated rows

# (label, CEN, GWEN, A, D, WEN, expected Q after this cycle's edge or None)
# WEN[i] = 0 writes bit i. Q is only loaded by reads (CEN=0, GWEN=1).
M32 = 0xFFFFFFFF
OPS = [
    ("idle-init", 1, 1, 0x00, 0x00000000, M32, None),
    ("write A7", 0, 0, 0xA7, 0xDEADBEEF, 0x00000000, None),
    ("write 3C", 0, 0, 0x3C, 0x12345678, 0x00000000, None),
    ("read A7", 0, 1, 0xA7, 0x00000000, M32, 0xDEADBEEF),
    ("read 3C", 0, 1, 0x3C, 0x00000000, M32, 0x12345678),
    # per-bit mask: bits 15:0 masked (WEN=1), bits 31:16 written with ones
    ("masked write A7", 0, 0, 0xA7, 0xFFFFFFFF, 0x0000FFFF, 0x12345678),
    ("read A7 after mask", 0, 1, 0xA7, 0x00000000, M32, 0xFFFFBEEF),
    ("read 3C neighbour", 0, 1, 0x3C, 0x00000000, M32, 0x12345678),
    # CEN=1 with GWEN=0 and fresh data: no write, Q holds
    ("idle (CEN=1) no write", 1, 0, 0xA7, 0x00000000, 0x00000000, 0x12345678),
    ("read A7 after idle", 0, 1, 0xA7, 0x00000000, M32, 0xFFFFBEEF),
]


def edge(i):
    return FIRST_EDGE + PERIOD * i


def pwl(values, vdd="VDDC"):
    """values: list of 0/1 per op -> PWL string, change at edge(i)-SETUP."""
    pts = [f"0 {vdd if values[0] else 0}"]
    prev = values[0]
    for i, v in enumerate(values[1:], 1):
        if v != prev:
            t = edge(i) - SETUP
            pts.append(f"{t:g}n {vdd if prev else 0}")
            pts.append(f"{t + TRISE:g}n {vdd if v else 0}")
            prev = v
    return "PWL(" + " ".join(pts) + ")"


def reduced_array(w):
    """The reduced `sram_64x128_array`: only the rows OPS addresses, 20 fF stand-ins."""
    rows = sorted({o[3] >> 2 for o in OPS})
    pins = [f"WL{r}" for r in range(64)]
    for p in range(128):
        pins += [f"BL{p}", f"BLB{p}"]
    w(".subckt sram_64x128_array " + " ".join(pins) + " VDD VSS")
    for r in rows:
        for p in range(128):
            w(f"Xr{r}c{p} BL{p} BLB{p} WL{r} VDD VSS bitcell_6t")
    for p in range(128):
        w(f"Cbl{p} BL{p} VSS {BL_STANDIN_FF}f")
        w(f"Cblb{p} BLB{p} VSS {BL_STANDIN_FF}f")
    w(".ends")


def gen():
    out = []
    w = out.append
    w("* Macro write/read smoke testbench -- sram_256x32 top netlist (issue #203).")
    w("* GENERATED by sim/macro-smoke/smoke.py gen -- do not hand-edit.")
    w("*")
    w("* Claim: after a write, a read of the same address returns the written word;")
    w("* a per-bit-masked write changes only the unmasked bits; a read of another")
    w("* address is unaffected; Q holds across writes and idle cycles. FUNCTIONAL")
    w("* ONLY: one corner, no timing, no margin, no Monte Carlo. No cycle time or")
    w("* clock-to-Q is claimed (spec/periphery-architecture.md, 'What this record")
    w("* does not do'). The PVT characterisation stays with sim/read-snm, hold-snm,")
    w("* write-margin and access-time; this is not a signoff result.")
    w("*")
    w("* DUT: design/netlist/sram_256x32.spice -- the macro top, periphery in full")
    w("* (decoder, control, 32 I/O slices, 4:1 mux). The ONE substitution: run.sh")
    w("* copies that netlist into the scratch dir as ./sram_256x32.noarray.spice with")
    w("* the `.subckt sram_64x128_array` block deleted (ngspice keeps the FIRST of")
    w("* two same-named subckts, so it cannot be overridden), and the array is")
    w("* redefined below with only the rows this test addresses populated (the full")
    w("* 8,192-cell transient did not finish in 10 min on a shared host). Every bit line carries a lumped")
    w(f"* {BL_STANDIN_FF} fF stand-in for the other rows, the same single-number placeholder")
    w("* sim/access-time/ uses (real column C is layout-derived, #204/#205). There is")
    w("* NO wire RC on wordlines or bit lines, so this says nothing about the")
    w("* wordline RC gate (periphery record, 'Wordline RC gate').")
    w("* `@@REPO_ROOT@@` is substituted by run.sh, as in the other testbenches.")
    w(".include './corner.inc'")
    w("VVDD VDD 0 DC VDDC")
    w("VVSS VSS 0 DC 0")
    w(".include './sram_256x32.noarray.spice'")
    reduced_array(w)
    w("")
    n = len(OPS)
    t_end = edge(n - 1) + PERIOD
    clk = [f"0 0"]
    for i in range(n):
        e = edge(i)
        clk += [f"{e:g}n 0", f"{e + TRISE:g}n VDDC", f"{e + CLK_HIGH:g}n VDDC", f"{e + CLK_HIGH + TRISE:g}n 0"]
    w("VCLK CLK 0 PWL(" + " ".join(clk) + ")")
    w("VCEN CEN 0 " + pwl([o[1] for o in OPS]))
    w("VGWEN GWEN 0 " + pwl([o[2] for o in OPS]))
    for b in range(8):
        w(f"VA{b} A{b}_s 0 " + pwl([o[3] >> b & 1 for o in OPS]))
    for b in range(32):
        w(f"VD{b} D{b}_s 0 " + pwl([o[4] >> b & 1 for o in OPS]))
        w(f"VW{b} WEN{b}_s 0 " + pwl([o[5] >> b & 1 for o in OPS]))
    # driver resistance keeps the bracketed pin names out of source names
    for b in range(8):
        w(f"RA{b} A{b}_s A[{b}] 1")
    for b in range(32):
        w(f"RD{b} D{b}_s D[{b}] 1")
        w(f"RW{b} WEN{b}_s WEN[{b}] 1")
    pins = " ".join(
        [f"A[{b}]" for b in range(7, -1, -1)]
        + ["CEN", "GWEN", "CLK"]
        + [f"D[{b}]" for b in range(31, -1, -1)]
        + [f"WEN[{b}]" for b in range(31, -1, -1)]
        + [f"Q[{b}]" for b in range(31, -1, -1)]
    )
    w(f"XDUT {pins} VDD VSS sram_256x32")
    for b in range(32):
        w(f"CQ{b} Q[{b}] 0 20f")
    w("")
    w(".option method=gear reltol=2e-3 abstol=1e-12 itl4=100")
    w(f".tran 0.02n {t_end:g}n")
    for i, o in enumerate(OPS):
        if o[6] is None:
            continue
        ts = edge(i) + SAMPLE
        for b in range(32):
            w(f".meas tran q{b}_op{i} FIND v(Q[{b}]) AT={ts:g}n")
    w(".end")
    return "\n".join(out) + "\n"


def gen_klt():
    """klt sim circuit BODY of the same testbench (issue #217): no corner.inc,
    .tran, .meas or .end. The supply is `VVDD` (altered by the request's
    `corners.supply_v.vvdd` axis); every stimulus is a 0..1 PWL scaled by
    V(VDD) through a B-source, since a body cannot use `.param VDDC`."""
    out = []
    w = out.append
    w("* Macro write/read smoke -- klt sim circuit BODY (issue #217).")
    w("* GENERATED by sim/macro-smoke/smoke.py gen-klt -- do not hand-edit.")
    w("*")
    w("* Same circuit, reduced array and stimulus as tb_macro_write_read.spice, as a")
    w("* body for requests/macro_write_read.json: process/temperature come from the")
    w("* request's corners, the supply from `corners.supply_v.vvdd` (alters VVDD),")
    w("* and the stimuli track V(VDD) through B-sources. The DUT include is")
    w("* sram_256x32.noarray.spice, a checked-in copy of design/netlist/sram_256x32.spice")
    w("* with the `.subckt sram_64x128_array` block removed (ngspice keeps the first of")
    w("* two same-named subckts, and a body has no run.sh to strip it). Functional")
    w("* only; same Limits as the local testbench.")
    w(".include './sram_256x32.noarray.spice'")
    w("* PDK default params normally supplied by design.ngspice (via corner.inc)")
    for p in ("sw_stat_global=0", "sw_stat_mismatch=0", "mc_skew=3", "res_mc_skew=3", "cap_mc_skew=3", "fnoicor=0"):
        w(f".param {p}")
    w("VVDD VDD 0 DC 3.3")
    w("VVSS VSS 0 DC 0")
    reduced_array(w)
    w("")
    n = len(OPS)
    clk = ["0 0"]
    for i in range(n):
        e = edge(i)
        clk += [f"{e:g}n 0", f"{e + TRISE:g}n 1", f"{e + CLK_HIGH:g}n 1", f"{e + CLK_HIGH + TRISE:g}n 0"]
    w("V1CLK CLK_s 0 PWL(" + " ".join(clk) + ")")
    w("V1CEN CEN_s 0 " + pwl([o[1] for o in OPS], "1"))
    w("V1GWEN GWEN_s 0 " + pwl([o[2] for o in OPS], "1"))
    w("BCLK CLK 0 V='v(VDD)*v(CLK_s)'")
    w("BCEN CEN 0 V='v(VDD)*v(CEN_s)'")
    w("BGWEN GWEN 0 V='v(VDD)*v(GWEN_s)'")
    for b in range(8):
        w(f"V1A{b} A{b}_s 0 " + pwl([o[3] >> b & 1 for o in OPS], "1"))
        w(f"BA{b} A[{b}] 0 V='v(VDD)*v(A{b}_s)'")
    for b in range(32):
        w(f"V1D{b} D{b}_s 0 " + pwl([o[4] >> b & 1 for o in OPS], "1"))
        w(f"BD{b} D[{b}] 0 V='v(VDD)*v(D{b}_s)'")
        w(f"V1W{b} WEN{b}_s 0 " + pwl([o[5] >> b & 1 for o in OPS], "1"))
        w(f"BW{b} WEN[{b}] 0 V='v(VDD)*v(WEN{b}_s)'")
    pins = " ".join(
        [f"A[{b}]" for b in range(7, -1, -1)]
        + ["CEN", "GWEN", "CLK"]
        + [f"D[{b}]" for b in range(31, -1, -1)]
        + [f"WEN[{b}]" for b in range(31, -1, -1)]
        + [f"Q[{b}]" for b in range(31, -1, -1)]
    )
    w(f"XDUT {pins} VDD VSS sram_256x32")
    for b in range(32):
        w(f"CQ{b} Q[{b}] 0 20f")
    w(".option method=gear reltol=2e-3 abstol=1e-12 itl4=100")
    return "\n".join(out) + "\n"


def klt_request():
    """The klt sim request for gen_klt(): 27 corners, one FIND per sampled Q bit."""
    meas = []
    for i, o in enumerate(OPS):
        if o[6] is None:
            continue
        ts = edge(i) + SAMPLE
        for b in range(32):
            meas.append({"name": f"q{b}_op{i}", "spice": f".meas tran q{b}_op{i} FIND v(Q[{b}]) AT={ts:g}n", "unit": "V"})
    return {
        "netlist": "../testbench/tb_macro_write_read.klt.spice",
        "engine": "ngspice",
        "models": {"lib": "$PDK_ROOT/gf180mcuD/libs.tech/ngspice/sm141064.ngspice"},
        "corners": {
            "process": [{"name": "ff", "sections": ["ff"]}, {"name": "tt", "sections": ["typical"]}, {"name": "ss", "sections": ["ss"]}],
            "supply_v": {"vvdd": [2.97, 3.30, 3.63]},
            "temperature_c": [-40, 25, 125],
        },
        "analysis": {"kind": "tran", "args": f"0.02n {edge(len(OPS) - 1) + PERIOD:g}n"},
        "measurements": meas,
        "netlist_source": "schematic",
        "options": {"timeout_s": 1500},
    }


def check_klt(report):
    """Grade a `klt sim` report of klt_request(): per corner, rebuild every sampled
    Q word against that corner's own VDD. A corner with a missing/errored measurement
    is reported OPEN, never dropped. Exit 1 on any FAIL, 2 if only OPEN rows remain."""
    import json

    rep = json.load(open(report))
    fail = open_ = 0
    for c in rep["corners"]:
        vdd = c["supply_v"]["vvdd"]
        vals = {}
        for m in c["measurements"]:
            r = re.fullmatch(r"q(\d+)_op(\d+)", m["name"])
            if r and m.get("value") is not None:
                vals[(int(r.group(2)), int(r.group(1)))] = float(m["value"])
        bad = missing = 0
        for i, o in enumerate(OPS):
            if o[6] is None:
                continue
            got = 0
            und = 0
            for b in range(32):
                v = vals.get((i, b))
                if v is None:
                    missing += 1
                    continue
                if not (v < 0.2 * vdd or v > 0.8 * vdd):
                    und += 1
                got |= (1 if v > vdd / 2 else 0) << b
            if und or (not missing and got != o[6]):
                bad += 1
        status = "OPEN" if missing else ("FAIL" if bad else "PASS")
        fail += status == "FAIL"
        open_ += status == "OPEN"
        print(f"RESULT: {c['corner_id']} {status} (words_bad={bad} unmeasured_bits={missing})")
    print(f"RESULT: smoke = {'FAIL' if fail else 'OPEN' if open_ else 'PASS'} over {len(rep['corners'])} corners")
    return 1 if fail else 2 if open_ else 0


def check(log):
    vals = {}
    for m in re.finditer(r"^q(\d+)_op(\d+)\s*=\s*([-+0-9.eE]+)", open(log).read(), re.M):
        vals[(int(m.group(2)), int(m.group(1)))] = float(m.group(3))
    vdd = None
    bad = 0
    for i, o in enumerate(OPS):
        if o[6] is None:
            continue
        got = 0
        undefined = 0
        for b in range(32):
            v = vals.get((i, b))
            if v is None or not (v < 0.2 * 3.3 or v > 0.8 * 3.3):
                undefined += 1
            got |= (1 if (v or 0) > 3.3 / 2 else 0) << b
        ok = undefined == 0 and got == o[6]
        bad += not ok
        print(
            f"RESULT: op{i} [{o[0]}] Q = 0x{got:08X} expected 0x{o[6]:08X} "
            f"undefined_bits={undefined} {'PASS' if ok else 'FAIL'}"
        )
    print(f"RESULT: smoke = {'PASS' if bad == 0 else 'FAIL'}")
    return 1 if bad else 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--out", default="sim/macro-smoke/testbench/tb_macro_write_read.spice")
    gk = sub.add_parser("gen-klt")
    gk.add_argument("--out", default="sim/macro-smoke/testbench/tb_macro_write_read.klt.spice")
    gk.add_argument("--request-out", default="sim/macro-smoke/requests/macro_write_read.json")
    c = sub.add_parser("check")
    c.add_argument("log")
    ck = sub.add_parser("check-klt")
    ck.add_argument("report")
    a = ap.parse_args()
    if a.cmd == "gen":
        open(a.out, "w").write(gen())
    elif a.cmd == "gen-klt":
        import json

        open(a.out, "w").write(gen_klt())
        open(a.request_out, "w").write(json.dumps(klt_request(), indent=2) + "\n")
    elif a.cmd == "check-klt":
        sys.exit(check_klt(a.report))
    else:
        sys.exit(check(a.log))

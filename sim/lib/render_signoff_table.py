#!/usr/bin/env python3
"""Render an explicit per-corner, per-metric PASS/FAIL signoff table.

Closes the one remaining gap the 2026-08-17 curator pass on issue #25
identified against the five append-only evidence records the (since-retired,
#230 cutover) `run_corner_sweep.sh` launcher produced under `sim/*/records/`
(read SNM, hold SNM, write margin,
read access time, write access time -- all covering the ratified
process x temperature x voltage PVT matrix, `spec/sram.md` "Corner set",
27 distinct corner points): those records list raw measured values plus a
single aggregate `Overall: recorded` line, not an explicit per-corner
PASS/FAIL verdict against `spec/sram.md`'s Signoff definition.

This script does not re-run any simulation and does not modify any
committed record (`sim/`'s append-only rule, `sim/README.md` "Append-only
rule", stays intact). It only *derives* a rollup from records that are
already committed evidence, so it is safe to re-run at any time --
including after a future corner sweep supersedes one of today's records --
and its output should be regenerated (not hand-edited) whenever that
happens.

Verdict rule, per `spec/sram.md`'s Signoff definition ("### Signoff
definition"):
  - read SNM, hold SNM: PASS iff the recorded value is strictly > 0 V.
  - write margin (the write trip voltage, WTV, taken directly from the
    write-margin record's `write_trip_voltage_v` RESULT line per corner --
    the minimum bit-line/write-driver drive that still flips the cell, per
    spec/sram.md's "What must be measured, not just asserted"): PASS iff
    strictly > 0 V.
  - read/write access time: the spec only requires these be *recorded*
    (feeding Liberty views later), not compared against a numeric
    threshold -- so every corner with a valid measured value is marked
    RECORDED, not PASS/FAIL. A corner with no valid RESULT line (an
    OPEN result, see sim/README.md) is marked OPEN for any metric.

Usage:
    python3 sim/lib/render_signoff_table.py [repo-root]

Output: a Markdown document on stdout. The repo wraps this in
`sim/signoff-summary.md`, regenerated by re-running this script and
re-committing its output whenever any of the five source records is
superseded by a fresh sweep.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
# Ratified PVT matrix, spec/sram.md "Corner set" -- process x temperature x
# voltage. Imported from its single owner (#331), never re-derived here: the
# "Note on corner count" paragraph below renders the axis product into the
# committed sim/signoff-summary.md, so a private copy would let that artifact
# keep asserting a stale product after an axis change. Same order the
# retired `run_corner_sweep.sh` launcher iterated (and `deck_adapter.py`
# stages), so every record's corner ordering already matches this.
from corner_matrix import PROCESSES, TEMPS, VDDS, corner_ids  # noqa: E402
from repo_root import find_repo_root  # noqa: E402 (path-injected sibling import)

CORNER_ORDER = corner_ids()

# The five characterization families' append-only evidence, in one place:
# family -> (records dir relative to sim/, Claim substring, recorded metric
# key, unit). render() renders its verdicts from these,
# sim/lib/mint_sim_envelope.py mints its envelope from them (#128), and
# measurements/generate_report.py derives its worst-case rows from them --
# and sim/lib/parity_compare.py (#230 full-grid deck-mode parity) compares
# fleet results against them -- one owner so the four consumers cannot drift
# into comparing different records, different metrics, or mislabelling a
# metric's unit (#359: the comparator renders this unit on every
# max-|delta| line).
RECORD_CLAIMS = {
    "read-snm": ("read-snm/records", "read SNM", "read_snm_v", "V"),
    "hold-snm": ("hold-snm/records", "hold SNM", "hold_snm_v", "V"),
    "write-margin": ("write-margin/records", "write margin", "write_trip_voltage_v", "V"),
    "read-access": ("access-time/records", "read access time", "read_access_time_s", "s"),
    "write-access": ("access-time/records", "write access time", "write_access_time_s", "s"),
}

# Which of those families `spec/sram.md`'s "### Signoff definition"
# bounds: read SNM, hold SNM, and write margin must be strictly > 0 V at
# every corner, while the two access-time families are record-only (a
# measured value is RECORDED, never PASS/FAIL). render()'s verdict rule,
# mint_sim_envelope.py's limits/worst-case rollup, and
# measurements/generate_report.py's worst-case rows all branch on this one
# set, so the consumers cannot disagree about which rows take a threshold
# verdict.
BOUNDED_FAMILIES = frozenset({"read-snm", "hold-snm", "write-margin"})

# Display labels for the per-family lines and per-corner table columns
# render() emits (Source records, the per-corner header, and Aggregate),
# indexed by RECORD_CLAIMS family: every render() loop iterates
# RECORD_CLAIMS and looks its label up here, so a family added to
# RECORD_CLAIMS without a label is a loud KeyError, never a short section
# or a header that disagrees with the body (#488).
FAMILY_LABELS = {
    "read-snm": "Read SNM",
    "hold-snm": "Hold SNM",
    "write-margin": "Write margin",
    "read-access": "Read access time",
    "write-access": "Write access time",
}

RESULT_RE = re.compile(r"RESULT:\s*(\w+)\s*=\s*([-+0-9.eE]+)\s*;?")
ROW_RE = re.compile(r"^\s*-\s*\*\*(\S+)\*\*:\s*(.*)$")

# The committed Monte Carlo sample-sets, one per family that has one (family
# -> path relative to sim/). One owner, same rule as RECORD_CLAIMS above:
# sim/lib/parity_compare.py's MC mode (#230) compares the deck-mode run's
# per-sample values against exactly these documents, so the binding lives
# here beside the record bindings rather than inline in the comparator.
# read-access/write-access have no committed MC record, so no binding.
MC_SAMPLE_SETS = {
    "read-snm": "read-snm/mc/samples/20260921-124232-cf5e975.json",
    "hold-snm": "hold-snm/mc/samples/20260921-124534-cf5e975.json",
    "write-margin": "write-margin/mc/samples/20260921-124804-cf5e975.json",
}


def latest_record_for_claim(records_dir: Path, claim_substring: str) -> Path:
    """Return the most recent record file (by <record-id> filename, which
    sorts chronologically -- see sim/README.md's <record-id> convention)
    under records_dir whose Claim line contains claim_substring."""
    candidates = []
    for path in sorted(records_dir.glob("*.md")):
        text = path.read_text()
        for line in text.splitlines():
            if line.startswith("- **Claim**:") and claim_substring in line:
                candidates.append(path)
                break
    if not candidates:
        raise SystemExit(
            f"no record under {records_dir} has a Claim containing "
            f"{claim_substring!r}"
        )
    # <record-id> = <YYYYMMDD>-<HHMMSS>-<short-sha> sorts chronologically as
    # a plain string; take the lexicographically-last (= most recent).
    return sorted(candidates)[-1]


def parse_record(path: Path) -> dict[str, dict[str, float] | str]:
    """Parse a record's per-corner Result rows into
    {corner_id: {key: value, ...}} or {corner_id: "OPEN"} for an open
    result."""
    per_corner: dict[str, dict[str, float] | str] = {}
    for line in path.read_text().splitlines():
        m = ROW_RE.match(line)
        if not m:
            continue
        corner_id, rest = m.group(1), m.group(2)
        if corner_id.startswith("Overall"):
            continue
        if rest.startswith("OPEN"):
            per_corner[corner_id] = "OPEN"
            continue
        values = {k: float(v) for k, v in RESULT_RE.findall(rest)}
        if values:
            per_corner[corner_id] = values
    return per_corner


def fmt_v(x: float) -> str:
    return f"{x:.6f}"


def fmt_s(x: float) -> str:
    return f"{x:.4e}"


def verdict_threshold(value: float | None) -> str:
    if value is None:
        return "OPEN"
    return "PASS" if value > 0 else "FAIL"


def verdict_recorded(value: float | None) -> str:
    if value is None:
        return "OPEN"
    return "RECORDED"


def default_repo_root() -> Path:
    return find_repo_root(Path(__file__))


def fmt_value(value: float | None, unit: str) -> str:
    return "--" if value is None else (fmt_v if unit == "V" else fmt_s)(value)


def render(repo_root: Path) -> str:
    """Render the signoff-summary Markdown for the records latest under
    repo_root -- the single derivation sim/signoff-summary.md commits and
    measurements/generate_report.py embeds in-process."""
    sim_dir = repo_root / "sim"

    # The five records come from RECORD_CLAIMS (see its comment): same
    # (records dir, Claim substring) pairs render() has always resolved, now
    # shared with parity_compare.py, mint_sim_envelope.py, and
    # measurements/generate_report.py.
    records = {
        family: latest_record_for_claim(sim_dir / records_rel, claim)
        for family, (records_rel, claim, _metric, _unit) in RECORD_CLAIMS.items()
    }
    parsed = {family: parse_record(record) for family, record in records.items()}

    # Per-family working state, all keyed (and therefore ordered) by
    # RECORD_CLAIMS: the per-corner measured value, its verdict, and the
    # [verdicted, total] counter the Aggregate section reports. Bounded
    # families (BOUNDED_FAMILIES) take the strictly-> 0 V threshold
    # verdict; the two access-time families are record-only.
    values: dict[str, dict[str, float | None]] = {
        family: {
            corner: vals.get(metric) if isinstance(vals, dict) else None
            for corner, vals in parsed[family].items()
        }
        for family, (_records_rel, _claim, metric, _unit) in RECORD_CLAIMS.items()
    }
    counts: dict[str, list[int]] = {family: [0, 0] for family in RECORD_CLAIMS}
    all_pass = True

    rows = []
    for corner in CORNER_ORDER:
        corner_values = {
            family: values[family].get(corner) for family in RECORD_CLAIMS
        }
        verdicts = {
            family: (
                verdict_threshold(corner_values[family])
                if family in BOUNDED_FAMILIES
                else verdict_recorded(corner_values[family])
            )
            for family in RECORD_CLAIMS
        }
        for family, verdict in verdicts.items():
            counts[family][1] += 1
            if verdict in ("PASS", "RECORDED"):
                counts[family][0] += 1

        if any(
            verdicts[family] != "PASS"
            for family in RECORD_CLAIMS
            if family in BOUNDED_FAMILIES
        ):
            all_pass = False

        row_overall = (
            "PASS"
            if all(
                verdicts[family] == "PASS"
                for family in RECORD_CLAIMS
                if family in BOUNDED_FAMILIES
            )
            else "FAIL"
        )

        rows.append(
            {
                "corner": corner,
                "values": corner_values,
                "verdicts": verdicts,
                "row_overall": row_overall,
            }
        )

    def rel(p: Path) -> str:
        return str(p.relative_to(repo_root))

    lines = []
    lines.append("# PVT signoff summary (derived, per-corner pass/fail)")
    lines.append("")
    lines.append(
        "Auto-generated by `sim/lib/render_signoff_table.py` -- do not hand-edit."
        " Regenerate with:"
    )
    lines.append("")
    lines.append(
        "```bash\npython3 sim/lib/render_signoff_table.py > sim/signoff-summary.md\n```"
    )
    lines.append("")
    lines.append(
        "This document derives an explicit **per-corner, per-metric PASS/FAIL"
        " verdict** from the five append-only evidence records already"
        " committed under `sim/*/records/` (see `sim/README.md` for the"
        " record format and the append-only convention). It does not run any"
        " simulation and does not modify those records -- it is a read-only"
        " rollup, closing the one gap the 2026-08-17 curation pass on issue"
        " #25 identified: the source records report raw measured values plus"
        " a single aggregate `Overall: recorded` line, not a per-corner"
        " verdict against `spec/sram.md`'s Signoff definition."
    )
    lines.append("")
    lines.append("## Source records")
    lines.append("")
    for family in RECORD_CLAIMS:
        label = FAMILY_LABELS[family]
        entry = f"- {label}: `{rel(records[family])}`"
        if family == "write-margin":
            entry += (
                " (margin is `write_trip_voltage_v` (WTV) directly -- the minimum"
                " write-driver drive that still flips the cell)"
            )
        lines.append(entry)
    lines.append("")
    lines.append(
        "## Verdict rule (`spec/sram.md`, \"### Signoff definition\")"
    )
    lines.append("")
    lines.append(
        "- Read SNM, hold SNM, write margin: **PASS** iff the recorded value"
        " is strictly `> 0` V; **FAIL** otherwise; **OPEN** if the source"
        " record has no valid measurement for that corner (see"
        " `sim/README.md` \"Append-only rule\")."
    )
    lines.append(
        "- Read/write access time: `spec/sram.md` only requires these be"
        " **recorded**, not compared against a numeric threshold, so a"
        " corner with a valid measured value is marked **RECORDED**, not"
        " PASS/FAIL."
    )
    lines.append("")
    lines.append(
        f"**Note on corner count**: the table below has {len(CORNER_ORDER)}"
        " rows, one per distinct `process x temperature x voltage`"
        " combination in the ratified corner matrix"
        f" `sim/lib/corner_matrix.py` (`{len(PROCESSES)} x {len(TEMPS)} x"
        f" {len(VDDS)} = {len(CORNER_ORDER)}`; the committed records were"
        " swept by the `run_corner_sweep.sh` launcher that #230's deck-mode"
        " cutover retired, over this same matrix), matching every one of the"
        " five source"
        " records above (each has exactly this many `- **<corner-id>**:`"
        " rows) and `spec/sram.md`'s \"Corner set\" section. That section"
        " computed the same product as \"9 corners\" until #53 corrected"
        " the arithmetic (3 x 3 x 3 = 27, not 9) -- see"
        " `spec/corner-count-correction.md`; the corner set, the Signoff"
        " definition, and every verdict below are unchanged by that"
        " correction. Records written before it still say \"9 corner"
        " points\" in their own generated prose while listing all 27 rows,"
        " because records are never edited after the fact"
        " (`sim/README.md`, \"Append-only rule\")."
    )
    lines.append("")
    lines.append("## Per-corner results")
    lines.append("")
    header = ["Corner"]
    for family, (_records_rel, _claim, _metric, unit) in RECORD_CLAIMS.items():
        header.append(f"{FAMILY_LABELS[family]} ({unit})")
        header.append("Verdict")
    header.append("Row overall (SNM + margin)")
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "---|" * len(header))
    for r in rows:
        cells = [r["corner"]]
        for family, (_records_rel, _claim, _metric, unit) in RECORD_CLAIMS.items():
            cells.append(fmt_value(r["values"][family], unit))
            cells.append(r["verdicts"][family])
        cells.append(r["row_overall"])
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    lines.append("## Aggregate")
    lines.append("")
    for family in RECORD_CLAIMS:
        label = FAMILY_LABELS[family]
        verdicted, total = counts[family]
        if family in BOUNDED_FAMILIES:
            unit = RECORD_CLAIMS[family][3]
            fmt = fmt_v if unit == "V" else fmt_s
            worst = min(
                (
                    r["values"][family]
                    for r in rows
                    if r["values"][family] is not None
                ),
                default=None,
            )
            lines.append(
                f"- {label}: {verdicted}/{total} PASS"
                f" (min {fmt(worst) if worst is not None else 'n/a'} {unit})"
            )
        else:
            lines.append(f"- {label}: {verdicted}/{total} RECORDED")
    lines.append("")
    overall = "PASS" if all_pass else "FAIL"
    lines.append(
        f"**Overall signoff (read SNM + hold SNM + write margin, all"
        f" {len(CORNER_ORDER)} corner points, per `spec/sram.md`'s Signoff"
        f" definition): {overall}.**"
    )
    lines.append("")
    lines.append(
        "Footnote on write-margin resolution: issue #47 (WTV recorded at the"
        " first *failing* sweep step rather than the last *succeeding* one)"
        " was fixed in #54 and closed; the write-margin record cited above is"
        " a post-fix re-run, so that off-by-one does not apply to any number"
        " in this table. What remains is the search's inherent resolution:"
        " `tb_write_margin.spice` sweeps the trip voltage on a `VDD/40` grid"
        " (~0.074 V at 2.97 V, ~0.091 V at 3.63 V), so the true trip point"
        " lies within one step above each recorded WTV and every write margin"
        " above is optimistic by at most one step. That bound is ~17x smaller"
        " than the smallest margin in the table, so no corner's PASS verdict"
        " turns on it."
    )
    lines.append("")

    return "\n".join(lines) + "\n"


def main() -> int:
    repo_root = Path(sys.argv[1]) if len(sys.argv) > 1 else default_repo_root()
    sys.stdout.write(render(repo_root))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
